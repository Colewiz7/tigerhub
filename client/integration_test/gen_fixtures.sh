#!/bin/sh
# writes integration_test/fixtures.g.dart from the captured test fixtures
# the app on the simulator cant read test/, so the data rides in as dart
set -eu
cd "$(dirname "$0")/.."
out=integration_test/fixtures.g.dart

emit() {
  # raw strings end at ''', so refuse a file that has one
  if grep -q "'''" "$2"; then echo "$2 contains ''', cant embed" >&2; exit 1; fi
  printf "const %s = r'''" "$1" >> "$out"
  cat "$2" >> "$out"
  printf "''';\n\n" >> "$out"
}

printf '// generated by gen_fixtures.sh, dont edit\n// ignore_for_file: type=lint\n\n' > "$out"
emit diningJson test/golden/dining.json
emit eventsJson test/golden/events.json
emit chefsJson test/golden/dining_visiting-chefs.json
emit specialsJson test/golden/dining_specials.json
emit occupancy23Json test/golden/dining_23_occupancy.json
emit housingJson test/golden/housing_areas.json
emit postOfficesJson test/golden/post-offices.json
emit recreationJson test/golden/recreation_hours.json
emit makerspaceHoursJson test/golden/makerspace_hours.json
emit makerspaceRoomsJson test/golden/makerspace_rooms.json
emit placeKindsJson test/golden/campus_places.json
emit mapCategory35 test/fixtures/maps_category_35.data
